import fs from 'node:fs'
import path from 'node:path'
import solc from 'solc'

const root = process.cwd()
const sourcePath = path.join(root, 'contracts', 'MachinaCountdown1155.sol')
const outputPath = path.join(root, 'src', 'countdown', 'contractArtifact.generated.ts')

// Keep the readable source focused on the artwork implementation, but compile the
// smoke-test V6 with a lightweight mint path. ERC-1155 explorers can read uri(id)
// directly; emitting the full base64 PNG+SVG metadata in every mint log is both
// unnecessary and extremely expensive for gas estimation.
const source = fs.readFileSync(sourcePath, 'utf8')
  .replace(
    'uint8 public constant METADATA_VERSION = 5;',
    'uint8 public constant METADATA_VERSION = 6;',
  )
  .replace(
    'emit TransferSingle(msg.sender,address(0),to,id,amount); emit URI(this.uri(id),id); _checkReceiver',
    'emit TransferSingle(msg.sender,address(0),to,id,amount); _checkReceiver',
  )

if (source.includes('emit URI(this.uri(id),id)')) {
  throw new Error('V6 compile guard failed: heavy URI event is still present in the mint path.')
}

const input = {
  language: 'Solidity',
  sources: {
    'MachinaCountdown1155.sol': { content: source },
  },
  settings: {
    optimizer: { enabled: true, runs: 200 },
    outputSelection: {
      '*': {
        '*': ['abi', 'evm.bytecode.object'],
      },
    },
  },
}

const output = JSON.parse(solc.compile(JSON.stringify(input)))
const errors = (output.errors ?? []).filter((entry) => entry.severity === 'error')
if (errors.length > 0) {
  console.error(errors.map((entry) => entry.formattedMessage).join('\n'))
  process.exit(1)
}

const artifact = output.contracts?.['MachinaCountdown1155.sol']?.MachinaCountdown1155
if (!artifact?.evm?.bytecode?.object) {
  throw new Error('MachinaCountdown1155 bytecode was not produced.')
}

const file = `// AUTO-GENERATED by scripts/compile-countdown-contract.mjs. Do not edit.\n` +
  `export const COUNTDOWN_DEPLOY_ABI = ${JSON.stringify(artifact.abi, null, 2)} as const\n` +
  `export const COUNTDOWN_DEPLOY_BYTECODE = '0x${artifact.evm.bytecode.object}' as const\n`

fs.writeFileSync(outputPath, file)
console.log('Generated countdown deployment artifact (metadata V6, lightweight mint).')
