// Compiles scripts/contracts/SwapSimulator.sol and (re)writes or verifies src/lib/swap/simulatorCode.ts.
//   node scripts/build-swap-simulator.mjs          write the generated module
//   node scripts/build-swap-simulator.mjs --check  fail if the module does not match a fresh compile (used by the verification suite)
// The contract is a READ-ONLY helper that only ever runs inside an eth_call state override (it is never deployed). Metadata is
// disabled so the runtime bytecode is reproducible for a given compiler version.
import { createRequire } from 'node:module'
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { createHash } from 'node:crypto'
const require = createRequire(import.meta.url), solc = require('solc')
const root = fileURLToPath(new URL('..', import.meta.url))
const source = readFileSync(`${root}scripts/contracts/SwapSimulator.sol`, 'utf8')
const output = JSON.parse(solc.compile(JSON.stringify({ language: 'Solidity', sources: { 'SwapSimulator.sol': { content: source } }, settings: {
  optimizer: { enabled: true, runs: 200 }, evmVersion: 'paris', metadata: { bytecodeHash: 'none', appendCBOR: false }, outputSelection: { '*': { '*': ['abi', 'evm.deployedBytecode.object'] } } } })))
if (output.errors?.some(e => e.severity === 'error')) { console.error(output.errors.map(e => e.formattedMessage).join('\n')); process.exit(1) }
const contract = output.contracts['SwapSimulator.sol'].SwapSimulator
const runtime = `0x${contract.evm.deployedBytecode.object}`
const sourceHash = createHash('sha256').update(source).digest('hex')
const body = `// GENERATED by scripts/build-swap-simulator.mjs from scripts/contracts/SwapSimulator.sol. Do not edit by hand.
// A read-only simulation helper injected as \`code\` in an eth_call state override. It is never deployed and holds no funds.
export const SIMULATOR_SOURCE_SHA256 = '${sourceHash}'
export const SIMULATOR_COMPILER = '${solc.version()}'
export const SIMULATOR_RUNTIME = '${runtime}' as const
export const SIMULATOR_ABI = ${JSON.stringify(contract.abi)} as const
`
const target = `${root}src/lib/swap/simulatorCode.ts`
if (process.argv.includes('--check')) {
  const current = readFileSync(target, 'utf8')
  if (current !== body) { console.error('simulatorCode.ts does not match a fresh compile of SwapSimulator.sol'); process.exit(1) }
  console.log('simulatorCode.ts matches a fresh compile', `(solc ${solc.version()}, ${(runtime.length - 2) / 2} bytes)`)
} else { writeFileSync(target, body); console.log('wrote', target, `${(runtime.length - 2) / 2} bytes`) }
